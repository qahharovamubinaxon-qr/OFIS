def region_of_series(series: str | None) -> str:
    """«50» → «Московская область». Unknown or missing → empty string."""
    code = re.sub(r"\D", "", series or "")
    if not code:
        return ""
    code = _EXTRA.get(code, code)
    if len(code) == 1:
        code = f"0{code}"
    return _NAMES.get(code, "")
