def birth_country(place: str | None, fallback: str | None = None) -> str:
    """Country (Title case) for a passport's birth place; ``fallback`` is the
    citizenship, used when the place cannot be classified."""
    up = (place or "").upper()
    if up:
        for country in _COUNTRIES:
            if country in up:
                return country.title()
        for region, country in _REGION_TO_COUNTRY.items():
            if region in up:
                return country.title()
    return (fallback or "").strip().title()
